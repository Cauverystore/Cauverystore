// Release signing is read from android/keystore.properties, which is never committed.
// Without it, only debug builds can be made.
val keystoreProps = Properties().apply {
    val f = rootProject.file("keystore.properties")
    if (f.exists()) f.inputStream().use { load(it) }
}

android {
    // Kotlin can't use "in" as a package name, so the code lives in com.cauverystore.android.
    // The installed app ID stays in.cauverystore.app so this replaces the earlier website wrapper.
    namespace = "com.cauverystore.android"
    compileSdk = 36

    defaultConfig {
        applicationId = "in.cauverystore.app"
        minSdk = 24
        targetSdk = 36
        versionCode = 2
        versionName = "2.0.0"

        buildConfigField("String", "API_BASE_URL", "\"https://cauvery-store-backend-production.up.railway.app/\"")
        buildConfigField("String", "WEBSITE_URL", "\"https://cauverystore.in\"")
    }

    signingConfigs {
        if (keystoreProps.getProperty("storeFile") != null) {
            create("release") {
                storeFile = rootProject.file(keystoreProps.getProperty("storeFile"))
                storePassword = keystoreProps.getProperty("storePassword")
                keyAlias = keystoreProps.getProperty("keyAlias")
                keyPassword = keystoreProps.getProperty("keyPassword")
            }
        }
    }

    buildTypes {
        release {
            isMinifyEnabled = true
            proguardFiles(getDefaultProguardFile("proguard-android-optimize.txt"), "proguard-rules.pro")
            signingConfigs.findByName("release")?.let { signingConfig = it }
        }
    }

    compileOptions {
        sourceCompatibility = JavaVersion.VERSION_17
        targetCompatibility = JavaVersion.VERSION_17
    }
    buildFeatures {
        compose = true
        buildConfig = true
    }
    androidResources {
        generateLocaleConfig = true
    }
}

